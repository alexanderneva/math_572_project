m = 0; n=0; p=0;
a = 3; b = 1; c =1; d=2;
A = [0,b,c;a,0,d; c,d,0];
theta = linspace(0,pi,16);
phi = linspace(0,2*pi,16);
[x,y,z] = sph2cart(phi,theta,1);
ini = [x; y; z];
r=-.5;
s=-0.5;
q=-0.5;
w = [r;s;q];
x_star = -inv(A)*w;
sys = @(A,w,v) A*v+w;
[vecs, lambda] = eig(A);
[X,Y,Z] = meshgrid(linspace(-1,1,20));
U = A(1,1)*X + A(1,2)*Y + A(1,3)*Z + w(1);
V = A(2,1)*X + A(2,2)*Y + A(2,3)*Z + w(2);
W = A(3,1)*X + A(3,2)*Y + A(3,3)*Z + w(3);
hold on;
quiver3(X,Y,Z,U,V,W,0);
plot3(x_star(1),x_star(2),x_star(3));
hold off;
